// Writes the guarded database migration (and its rollback) for the approved price list. Run after `npm run build`.
// The migration is NOT applied by this script.
import {readFile,writeFile} from 'node:fs/promises';
import {APPROVED_UPDATES,APPROVED_NEW_VARIANTS,APPROVED_NEW_PRODUCTS,PRICE_LIST_DATE} from '../commerce/approved-prices-2026-11-16.mjs';
const rows=JSON.parse(await readFile('assets/shop-data.json','utf8')),bySku=new Map(rows.map(r=>[r.sku,r]));
const q=v=>v===null||v===undefined?'null':typeof v==='number'?String(v):"'"+String(v).replace(/'/g,"''")+"'";
const json=o=>q(JSON.stringify(o))+'::jsonb';
const tag=PRICE_LIST_DATE.replaceAll('-','');
const updated=APPROVED_UPDATES.map(u=>u.sku);
const insertedSkus=[...APPROVED_NEW_VARIANTS.map(n=>n.slug+'|'+n.variant.storage),...APPROVED_NEW_PRODUCTS.flatMap(p=>p.variants.map(v=>p.slug+'|'+v.storage))];
const fieldsFor=sku=>{const r=bySku.get(sku);if(!r)throw Error('Not in built catalogue: '+sku);return r;};
const pick=(r,keys)=>Object.fromEntries(keys.filter(k=>r[k]!==undefined).map(k=>[k,r[k]]));
let sql=`-- Approved price list ${PRICE_LIST_DATE}. Generated by scripts/build-price-migration.mjs — do not edit by hand.
-- NOT APPLIED. Review, then apply with the owner's approval in the same release as the code.
-- Every update is guarded by the current price and must hit exactly one row, or the whole migration rolls back.
begin;
create table if not exists public.checkout_inventory_backup_prices_${tag} as
 select * from public.checkout_inventory where sku in (${updated.map(q).join(',')});
create table if not exists public.shop_deal_settings_backup_${tag} as select * from public.shop_deal_settings;
alter table public.checkout_inventory_backup_prices_${tag} enable row level security;
alter table public.shop_deal_settings_backup_${tag} enable row level security;
do $$ declare n integer; begin
`;
for(const u of APPROVED_UPDATES){const r=fieldsFor(u.sku),data=pick(r,['condition','capacity','colors','connectivity','activation','simNote','colourNote','reviewRequired']);
 sql+=` update public.checkout_inventory set price_ngn=${u.price},enabled=true,product_data=product_data||${json({...data,price:u.price,enabled:true,reviewRequired:false})},updated_at=clock_timestamp()
  where sku=${q(u.sku)} and price_ngn is not distinct from ${q(u.before)};
 get diagnostics n=row_count; if n<>1 then raise exception 'Price guard failed for %',${q(u.sku)}; end if;
`;}
sql+=`end $$;
-- New variants and new products. Existing SKUs are never overwritten.
insert into public.checkout_inventory(sku,price_ngn,enabled,product_data) values
${insertedSkus.map(sku=>{const r=fieldsFor(sku);return ` (${q(sku)},${q(r.price)},${r.enabled&&r.price>0?'true':'false'},${json(r)})`;}).join(',\n')}
on conflict (sku) do nothing;
-- Latest iPhone series leaves Hot Deals (no automatic discount). Order of the remaining deals is kept.
update public.shop_deal_settings set skus=coalesce((select array_agg(s order by o) from unnest(skus) with ordinality u(s,o) where s !~ '^iphone-18(-|\\|)'),'{}'),revision=revision+1,updated_at=clock_timestamp() where id='store';
-- Publishing rules: iPhone 18 cannot be published as a Hot Deal; iPhone 17 and 18 may be Brand New or UK Used.
create or replace function public.shop_publish_hot_deals(p_actor uuid, p_skus text[], p_revision integer) returns jsonb language plpgsql set search_path to 'public' as $f$
begin
 if p_skus is not null and cardinality(p_skus)>4 then raise exception 'Select up to four unique variants';end if;
 if exists(select 1 from unnest(coalesce(p_skus,'{}')) s where s ~ '^iphone-18(-|\\|)') then raise exception 'The latest iPhone series cannot be a Hot Deal';end if;
 return shop_publish_deals(p_actor,p_skus,p_revision);
end $f$;
`;
sql+=`-- shop_admin_update_product: same as before except the iPhone condition rule now allows Brand New for iPhone 17.
create or replace function public.shop_admin_update_product(p_actor uuid, p_sku text, p_price bigint, p_enabled boolean, p_updated_at timestamp with time zone, p_data jsonb) returns jsonb language plpgsql set search_path to 'public' as $f$
declare old checkout_inventory%rowtype; saved checkout_inventory%rowtype;
begin
 if not exists(select 1 from auth.users where id=p_actor and exists(select 1 from public.shop_admins a where a.user_id=p_actor) and lower(email)='aderintomicheal6@gmail.com' and email_confirmed_at is not null) then raise exception 'Administrator access required';end if;
 if p_price<=0 or p_price>100000000 or (p_enabled and p_price is null) then raise exception 'Invalid price';end if;
 select * into old from checkout_inventory where sku=p_sku for update;
 if not found or old.updated_at is distinct from p_updated_at then raise exception 'Inventory changed; reload before editing';end if;
 if p_data->>'slug' is distinct from old.product_data->>'slug' or p_data->>'sku' is distinct from old.product_data->>'sku' or p_data->>'storage' is distinct from old.product_data->>'storage' then raise exception 'SKU identity is immutable';end if;
 if p_data->>'slug' like 'iphone-%' and (case when p_data->>'slug' ~ '^iphone-1[78]-' then p_data->>'condition' not in ('Brand New','UK Used') else p_data->>'condition' <> 'UK Used' end) then raise exception 'Invalid iPhone condition';end if;
 if p_enabled and coalesce((p_data->>'reviewRequired')::boolean,false) then raise exception 'Resolve catalogue review before enabling';end if;
 update checkout_inventory set price_ngn=p_price,enabled=p_enabled,product_data=p_data,updated_at=clock_timestamp() where sku=p_sku returning * into saved;
 insert into shop_admin_audit(actor_id,sku,previous_value,new_value) values(p_actor,p_sku,to_jsonb(old),to_jsonb(saved));
 return to_jsonb(saved);
end $f$;
commit;
`;
const rollback=`-- Rollback for ${PRICE_LIST_DATE} price migration. Restores the backed-up rows and deal list, removes only the rows
-- this migration inserted, and only if they have never been ordered.
begin;
update public.checkout_inventory c set price_ngn=b.price_ngn,enabled=b.enabled,product_data=b.product_data,updated_at=clock_timestamp()
 from public.checkout_inventory_backup_prices_${tag} b where c.sku=b.sku;
delete from public.checkout_inventory where sku in (${insertedSkus.map(q).join(',')})
 and not exists(select 1 from public.shop_order_items i where i.sku=checkout_inventory.sku);
update public.shop_deal_settings d set skus=b.skus,revision=d.revision+1,updated_at=clock_timestamp() from public.shop_deal_settings_backup_${tag} b where d.id=b.id;
create or replace function public.shop_publish_hot_deals(p_actor uuid, p_skus text[], p_revision integer) returns jsonb language plpgsql set search_path to 'public' as $f$
begin
 if p_skus is not null and cardinality(p_skus)>4 then raise exception 'Select up to four unique variants';end if;
 return shop_publish_deals(p_actor,p_skus,p_revision);
end $f$;
-- To restore the previous iPhone condition rule, re-run the function body from 20261114120000 or earlier.
commit;
`;
await writeFile(`supabase/migrations/${tag}120000_approved_prices.sql`,sql);
await writeFile(`supabase/prices-${tag}-rollback.sql`,rollback);
console.log('updates',APPROVED_UPDATES.length,'inserts',insertedSkus.length);
