// Build step (runs after the pages are generated). Records, for every product page, the facts Google Merchant
// Center needs that live in the website rather than in Supabase: the page address, which variants the page can
// show, and the product photos the page uses. Prices, availability and variants themselves come from Supabase.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {storeItems} from '../commerce/storefront-data.mjs';
import {products} from '../commerce/catalog.mjs';
const out={};
for(const item of storeItems){
 const route=item.route.replace(/\/?$/,'/'),file='.'+route+'index.html';
 if(!existsSync(file))continue;
 const html=readFileSync(file,'utf8');
 let skus=[];const data=html.match(/<script type="application\/json" id="product-data">([\s\S]*?)<\/script>/);
 if(data){try{skus=JSON.parse(data[1]).variants.map(v=>item.slug+'|'+v.storage);}catch{}}
 else skus=[...html.matchAll(/<select id="gadget-variant">([\s\S]*?)<\/select>/g)].flatMap(m=>[...m[1].matchAll(/<option value="([^"]+)"/g)].map(o=>o[1].replace(/&amp;/g,'&').replace(/&quot;/g,'"')));
 const photos=[...new Set([...(products.find(p=>p.slug===item.slug)?.images||[]),item.image].filter(u=>typeof u==='string'&&u.startsWith('/')&&existsSync('.'+u)))];
 out[item.slug]={route:item.route,model:item.model,brand:item.brand||'',category:item.category||'',skus,photos};
}
writeFileSync('commerce/merchant-products.mjs','// Generated by scripts/generate-merchant-data.mjs — do not edit by hand.\nexport default '+JSON.stringify(out)+';\n');
console.log(`Merchant page data for ${Object.keys(out).length} products`);
