// Follow-up to the 16 Nov price list: conditions confirmed by the owner (UK Used), iPhone Duo, owner photos.
// Writes the migration and its rollback. Run after `npm run build`. It is NOT applied by this script.
import {readFile,writeFile} from 'node:fs/promises';
import {APPROVED_NEW_PRODUCTS,OWNER_PHOTOS,ownerPhoto} from '../commerce/approved-prices-2026-11-16.mjs';
const rows=JSON.parse(await readFile('assets/shop-data.json','utf8')),bySku=new Map(rows.map(r=>[r.sku,r]));
const q=v=>v===null||v===undefined?'null':typeof v==='number'?String(v):"'"+String(v).replace(/'/g,"''")+"'";
const json=o=>q(JSON.stringify(o))+'::jsonb';
const confirmed=APPROVED_NEW_PRODUCTS.filter(p=>p.condition==='UK Used'&&!p.slug.startsWith('ipad-')).flatMap(p=>p.variants.map(v=>p.slug+'|'+v.storage));
const duo=APPROVED_NEW_PRODUCTS.find(p=>p.slug==='iphone-duo').variants.map(v=>'iphone-duo|'+v.storage);
const photoSkus=rows.filter(r=>OWNER_PHOTOS.includes(r.slug)).map(r=>r.sku);
const touched=[...confirmed,...photoSkus];
const row=sku=>{const r=bySku.get(sku);if(!r)throw Error('Not in built catalogue: '+sku);return r;};
let sql=`-- Follow-up 2026-11-16: owner confirmed UK Used for watches, keyboard cases, JBL and Harman Kardon;
-- iPhone Duo added (Brand New, eSIM only); owner-supplied photos for ${OWNER_PHOTOS.length} products.
-- Generated by scripts/build-followup-migration.mjs. Guarded: every change must hit the expected rows or it all rolls back.
begin;
create table if not exists public.checkout_inventory_backup_followup_20261116 as
 select * from public.checkout_inventory where sku in (${touched.map(q).join(',')});
alter table public.checkout_inventory_backup_followup_20261116 enable row level security;
do $$ declare n integer; begin
 update public.checkout_inventory set enabled=(price_ngn is not null),product_data=product_data||jsonb_build_object('condition','UK Used','enabled',price_ngn is not null),updated_at=clock_timestamp()
  where sku in (${confirmed.map(q).join(',')}) and product_data->>'condition'='Confirm condition';
 get diagnostics n=row_count; if n<>${confirmed.length} then raise exception 'Condition guard: expected ${confirmed.length} rows, got %',n; end if;
`;
for(const slug of OWNER_PHOTOS)sql+=` update public.checkout_inventory set product_data=product_data||${json({image:ownerPhoto(slug)})},updated_at=clock_timestamp()
  where product_data->>'slug'=${q(slug)} and coalesce(product_data->>'image','')='';
`;
sql+=`end $$;
insert into public.checkout_inventory(sku,price_ngn,enabled,product_data) values
${duo.map(sku=>{const r=row(sku);return ` (${q(sku)},${q(r.price)},true,${json(r)})`;}).join(',\n')}
on conflict (sku) do nothing;
-- iPhone Duo may be Brand New or UK Used in Admin, like iPhone 17 and 18.
create or replace function public.shop_admin_update_product(p_actor uuid, p_sku text, p_price bigint, p_enabled boolean, p_updated_at timestamp with time zone, p_data jsonb) returns jsonb language plpgsql set search_path to 'public' as $f$
declare old checkout_inventory%rowtype; saved checkout_inventory%rowtype;
begin
 if not exists(select 1 from auth.users where id=p_actor and exists(select 1 from public.shop_admins a where a.user_id=p_actor) and lower(email)='aderintomicheal6@gmail.com' and email_confirmed_at is not null) then raise exception 'Administrator access required';end if;
 if p_price<=0 or p_price>100000000 or (p_enabled and p_price is null) then raise exception 'Invalid price';end if;
 select * into old from checkout_inventory where sku=p_sku for update;
 if not found or old.updated_at is distinct from p_updated_at then raise exception 'Inventory changed; reload before editing';end if;
 if p_data->>'slug' is distinct from old.product_data->>'slug' or p_data->>'sku' is distinct from old.product_data->>'sku' or p_data->>'storage' is distinct from old.product_data->>'storage' then raise exception 'SKU identity is immutable';end if;
 if p_data->>'slug' like 'iphone-%' and (case when p_data->>'slug' ~ '^iphone-(1[78]|duo)(-|$)' then p_data->>'condition' not in ('Brand New','UK Used') else p_data->>'condition' <> 'UK Used' end) then raise exception 'Invalid iPhone condition';end if;
 if p_enabled and coalesce((p_data->>'reviewRequired')::boolean,false) then raise exception 'Resolve catalogue review before enabling';end if;
 update checkout_inventory set price_ngn=p_price,enabled=p_enabled,product_data=p_data,updated_at=clock_timestamp() where sku=p_sku returning * into saved;
 insert into shop_admin_audit(actor_id,sku,previous_value,new_value) values(p_actor,p_sku,to_jsonb(old),to_jsonb(saved));
 return to_jsonb(saved);
end $f$;
commit;
`;
await writeFile('supabase/migrations/20261116150000_uk_used_duo_photos.sql',sql);
await writeFile('supabase/followup-20261116-rollback.sql',`-- Rollback for 20261116150000_uk_used_duo_photos.sql
begin;
update public.checkout_inventory c set price_ngn=b.price_ngn,enabled=b.enabled,product_data=b.product_data,updated_at=clock_timestamp()
 from public.checkout_inventory_backup_followup_20261116 b where c.sku=b.sku;
-- iPhone Duo rows are switched off rather than deleted, so any order that references them stays intact.
update public.checkout_inventory set enabled=false,product_data=product_data||'{"enabled":false}'::jsonb,updated_at=clock_timestamp() where sku in (${duo.map(q).join(',')});
commit;
`);
console.log('confirmed',confirmed.length,'duo',duo.length,'photo skus',photoSkus.length);
